"""Aggregate raw results into CSV/LaTeX tables and a REPORT.md that states which paper claims the new numbers support.

    python -m gcids.report --results results
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from .stats import (CLS_KEYS, DIRECTION, EMB_KEYS, aggregate, dial_correlation, load_genq, load_results, paired_table,
                    to_latex)
from .utils import get_logger

log = get_logger()

MAIN_ORDER = ["S0", "S1", "C1", "C1b-noise", "C1b-mixup", "C2-VAE", "C2-GAN", "SupCon", "C3-realpair", "GC-mask-GAN",
              "GC-mask-VAE", "SCARF", "LightGBM", "FT-Transformer"]
PAPER_ORDER = ["S0", "S1", "C1", "C1b-noise", "C1b-mixup", "C2-VAE", "C2-GAN"]
PRIMARY_REF = "C2-GAN"
PRIMARY_B = ["C1b-noise", "C1", "SupCon", "C3-realpair", "S0", "C2-VAE", "GC-mask-GAN"]
PAIR_METRICS = ["accuracy", "macro_f1", "g_mean", "rare_recall", "rare_f1", "silhouette", "davies_bouldin", "intra_inter",
                "alignment", "uniformity", "knn_acc"]
# paper numbers (3 seeds, old code) used only as reproduction targets
TARGETS = {
    "nslkdd": {"S0": (.7847, .5954), "S1": (.7780, .5641), "C1": (.7807, .5905), "C1b-noise": (.8005, .6146),
               "C1b-mixup": (.7817, .5928), "C2-VAE": (.7600, .5475), "C2-GAN": (.7762, .5748)},
    "unswnb15": {"S0": (.6440, .3937), "S1": (.7358, .3878), "C1": (.6513, .4133), "C1b-noise": (.6194, .3614),
                 "C1b-mixup": (.6276, .3712), "C2-VAE": (.6482, .3945), "C2-GAN": (.6514, .4033)},
}
TARGET_MMD = {"nslkdd": {"vae": 0.4944, "gan": 0.1238}}


def _md(df: pd.DataFrame, digits: int = 4) -> str:
    if df is None or df.empty:
        return "_(no data)_"
    d = df.copy()
    if not isinstance(d.index, pd.RangeIndex):
        d = d.reset_index()
    for c in d.columns:
        if d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.{digits}f}")
    cols = list(d.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in d.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def _pm(agg: pd.DataFrame, metrics: list[str], digits: int = 4) -> pd.DataFrame:
    out = pd.DataFrame(index=agg.index)
    for m in metrics:
        out[m] = [f"{a:.{digits}f} ± {s:.{digits}f}" if not pd.isna(s) else f"{a:.{digits}f}" for a, s in zip(agg[m], agg[m + "_std"])]
    out["n"] = agg["n_seeds"]
    out.index.name = "variant"
    return out


def build(results_dir: str | Path) -> str:
    rd = Path(results_dir)
    tdir = rd / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    df, genq = load_results(rd), load_genq(rd)
    if df.empty:
        return "# REPORT\n\nNo results found."
    md = ["# REPORT (auto-generated by `python -m gcids.report`)", "",
          "All numbers are mean ± std over seeds on the official test split (CIC-IDS2017: fixed 70/30 split). "
          "Model selection used the validation split only. Re-run numbers differ from the original paper tables "
          "because the original code was lost and this is a clean re-implementation (see DECISIONS.md).", ""]
    claims: list[str] = []
    for ds in sorted(df.dataset.unique()):
        d = df[df.dataset == ds]
        present = [v for v in MAIN_ORDER if v in set(d.variant)]
        n_seeds = int(d.groupby("variant").seed.nunique().max())
        md += [f"## {ds}", f"Seeds per variant (max): {n_seeds}.", ""]
        # ---- classification
        agg = aggregate(df, ds, CLS_KEYS, "mlp", present)
        agg.to_csv(tdir / f"main_cls_{ds}.csv")
        md += ["### Classification (MLP probe on the frozen encoder; S0/S1 end-to-end)", _md(_pm(agg, ["accuracy", "macro_f1", "g_mean", "rare_recall", "rare_f1", "mcc"])), ""]
        agg_l = aggregate(df, ds, CLS_KEYS, "linear", present)
        agg_l.to_csv(tdir / f"main_cls_linear_{ds}.csv")
        md += ["### Classification (linear probe on the frozen encoder)", _md(_pm(agg_l, ["accuracy", "macro_f1", "g_mean", "rare_f1"])), ""]
        # ---- embedding
        contr = [v for v in present if v not in ("LightGBM", "FT-Transformer")]
        aggE = aggregate(df, ds, EMB_KEYS, "mlp", contr)
        aggE.to_csv(tdir / f"main_emb_{ds}.csv")
        md += ["### Embedding quality (silhouette↑ DB↓ intra/inter↓ alignment↓ uniformity↓ kNN↑)", _md(_pm(aggE, EMB_KEYS)), ""]
        # ---- paired tests
        pairs = [(PRIMARY_REF, b) for b in PRIMARY_B if b in present and PRIMARY_REF in present]
        pt = paired_table(df, ds, pairs, PAIR_METRICS, "mlp")
        if len(pt):
            pt.to_csv(tdir / f"paired_{ds}.csv", index=False)
            show = pt[pt.metric.isin(["macro_f1", "g_mean", "rare_f1", "silhouette", "davies_bouldin"])][
                ["metric", "A", "B", "n", "mean_diff", "ci_boot_lo", "ci_boot_hi", "dz", "t_p_holm", "wilcoxon_p_holm", "min_wilcoxon_p"]]
            md += [f"### Paired tests, {PRIMARY_REF} vs reference (A−B; Holm within metric)",
                   "With n seeds the smallest attainable exact two-sided Wilcoxon p is 2/2^n (n=3: 0.25; n=6: 0.031).", _md(show.reset_index(drop=True)), ""]
            # automatic claim checks
            def row(m, b):
                r = pt[(pt.metric == m) & (pt.B == b)]
                return r.iloc[0] if len(r) else None
            for b in ("C1b-noise", "C1"):
                r = row("macro_f1", b)
                if r is not None:
                    verdict = ("INCONCLUSIVE (n<6, exact Wilcoxon cannot reach p<0.05)" if r.n < 6 else
                               ("C2-GAN significantly better" if r.mean_diff > 0 and r.t_p_holm < 0.05 else
                                "C2-GAN significantly worse" if r.mean_diff < 0 and r.t_p_holm < 0.05 else "no significant difference"))
                    claims.append(f"[{ds}] Macro-F1, C2-GAN − {b}: {r.mean_diff:+.4f} (Holm t-test p={r.t_p_holm:.3g}) -> {verdict}")
            for b in ("C1b-noise", "C1"):
                for m in ("silhouette", "davies_bouldin"):
                    r = row(m, b)
                    if r is not None:
                        better = "same" if abs(r.mean_diff) < 1e-12 else ("better" if (r.mean_diff > 0) == (DIRECTION[m] > 0) else "worse")
                        claims.append(f"[{ds}] {m}, C2-GAN vs {b}: diff {r.mean_diff:+.4f}, GC is {better} "
                                      f"(Holm t p={r.t_p_holm:.3g}, n={int(r.n)})")
            r = row("macro_f1", "SupCon")
            if r is not None:
                claims.append(f"[{ds}] Label-supervision control: C2-GAN − SupCon Macro-F1 {r.mean_diff:+.4f} (p={r.t_p_holm:.3g}); "
                              "if SupCon >= C2-GAN, 'GC adds value beyond label-driven pairing' is NOT supported.")
            r = row("macro_f1", "C3-realpair")
            if r is not None:
                claims.append(f"[{ds}] Pairing control: C2-GAN − C3-realpair Macro-F1 {r.mean_diff:+.4f} (p={r.t_p_holm:.3g}); "
                              "if ~0, generated samples add nothing beyond same-class pairing.")
        # ---- reproduction targets
        if ds in TARGETS:
            rows = []
            for v, (acc0, f10) in TARGETS[ds].items():
                if v in agg.index:
                    rows.append({"variant": v, "acc_paper": acc0, "acc_new": agg.loc[v, "accuracy"], "f1_paper": f10, "f1_new": agg.loc[v, "macro_f1"]})
            rp = pd.DataFrame(rows)
            if len(rp):
                rp["acc_diff"] = rp.acc_new - rp.acc_paper
                rp["f1_diff"] = rp.f1_new - rp.f1_paper
                rp.to_csv(tdir / f"reproduction_{ds}.csv", index=False)
                md += ["### Reproduction vs the old paper numbers (diff = new − paper)", _md(rp), "",
                       "If differences exceed a few percent, say so in the paper and rewrite the affected claims."
                       " The new tables replace the old ones anyway.", ""]
        # ---- cost
        cc = [c for c in d.columns if c.startswith("cost:") and c.endswith(("seconds", "peak_gpu_mb", "n_params"))]
        if cc:
            cost = d[d.probe == "mlp"].groupby("variant", sort=False)[cc].mean().reindex(present)
            cost.to_csv(tdir / f"cost_{ds}.csv")
            keep = [c for c in cost.columns if any(s in c for s in ("generator_train:seconds", "pretrain:seconds", "pretrain:peak", "pretrain:n_params", "train:seconds", "generator_sample:seconds", "inference:seconds"))]
            md += ["### Cost (mean per run; seconds, MB, parameters)", _md(cost[keep].dropna(how="all"), 1), ""]
        # ---- generator quality
        if not genq.empty:
            g = genq[(genq.dataset == ds) & (genq.scope == "overall") & genq.checkpoint.isna()]
            if len(g):
                cols = ["mmd2", "wasserstein", "corr_diff", "precision", "recall", "density", "coverage", "c2st_auc", "memorisation"]
                ga = g.groupby("variant")[[c for c in cols if c in g]].agg(["mean", "std"])
                ga.columns = [f"{a}_{b}" for a, b in ga.columns]
                ga.to_csv(tdir / f"genq_{ds}.csv")
                md += ["### Generator quality (pooled over classes; MMD² unbiased RBF, mean over bandwidths)", _md(ga), ""]
                if ds in TARGET_MMD:
                    md += [f"Old paper MMD (NSL-KDD): cVAE {TARGET_MMD[ds]['vae']}, cGAN {TARGET_MMD[ds]['gan']} "
                           "(absolute values depend on the bandwidth rule; compare the ORDER).", ""]
        # ---- dial
        if not genq.empty:
            for fam in ("GAN", "VAE"):
                dc = dial_correlation(df, genq, ds, fam, ["macro_f1", "rare_f1", "silhouette"])
                if len(dc):
                    dc.to_csv(tdir / f"dial_{fam}_{ds}.csv", index=False)
                    md += [f"### Generator-quality dial ({fam}): Spearman(MMD², outcome) across checkpoints × seeds", _md(dc), ""]
        # ---- latex
        lat_m = ["accuracy", "macro_f1", "g_mean", "rare_f1"]
        dag = {}
        if len(pt):
            for _, r in pt.iterrows():
                if r.metric in lat_m and r.t_p_holm < 0.05:
                    dag[(r.B, r.metric)] = True
        (tdir / f"main_cls_{ds}.tex").write_text(to_latex(agg, lat_m, dag, f"Classification results on {ds} (mean$\\pm$std over seeds). $\\dagger$: differs from C2-GAN after Holm correction.", f"tab:cls_{ds}"))
        (tdir / f"main_emb_{ds}.tex").write_text(to_latex(aggE, EMB_KEYS, None, f"Embedding quality on {ds}.", f"tab:emb_{ds}"))
    md += ["## Automatic claim checks", ""] + [f"- {c}" for c in claims] + [""]
    md += ["## Reading guide",
           "- The paper's headline finding was: GC improves embedding geometry but plain Gaussian-noise SimCLR (C1b-noise) classifies as well or better.",
           "- Check SupCon and C3-realpair rows before claiming that the generator matters: they isolate the role of labels.",
           "- Alignment in the OLD Table 5 was marked higher-is-better by mistake; here lower is better.", ""]
    return "\n".join(md)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    a = ap.parse_args()
    text = build(a.results)
    out = Path(a.results) / "REPORT.md"
    out.write_text(text, encoding="utf-8")
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
