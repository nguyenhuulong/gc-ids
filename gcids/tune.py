"""Shared hyper-parameter tuning on the VALIDATION split of a tuning seed (never the test set).

One grid point is chosen for ALL contrastive methods (the one with the best mean validation Macro-F1 of the MLP probe over
the listed methods), so no method gets a private advantage. Output: configs/tuned_<dataset>.yaml, to be passed AFTER
base.yaml to gcids.run.

    python -m gcids.tune --dataset nslkdd --config configs/base.yaml configs/nslkdd.yaml --seed 0
"""
from __future__ import annotations

import argparse
import itertools
from pathlib import Path

import numpy as np
import yaml

from .data import prepare
from .run import run_variant
from .utils import get_device, get_logger, load_config

log = get_logger()


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--config", nargs="+", required=True)
    ap.add_argument("--seed", type=int, default=0, help="tuning seed; keep it OUT of the final seed list")
    ap.add_argument("--methods", nargs="+", default=["C1b-noise", "C2-GAN"])
    ap.add_argument("--tau", nargs="+", type=float, default=[0.1, 0.2, 0.5])
    ap.add_argument("--lr", nargs="+", type=float, default=[1e-3, 3e-4])
    ap.add_argument("--sigma", nargs="+", type=float, default=[0.05, 0.1])
    ap.add_argument("--data-root", default="data")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    base = load_config(*a.config)
    dev = get_device(a.device)
    sp = prepare(a.dataset, a.data_root, a.seed, base["data"].get("val_frac", 0.2), base["data"].get("rare_thresh", 0.015),
                 base["data"].get("strict_counts", True) and a.dataset != "toy")
    results = []
    for tau, lr, sigma in itertools.product(a.tau, a.lr, a.sigma):
        ov = {"pretrain": {"tau": tau, "lr": lr, "sigma": sigma}}
        f1s = []
        for m in a.methods:
            rec = run_variant(a.dataset, a.seed, f"tune-{m}", {"method": m, **ov}, base, sp, dev)
            f1s.append(rec["val_f1"]["mlp"])
        results.append({"tau": tau, "lr": lr, "sigma": sigma, "mean_val_f1": float(np.mean(f1s)), "val_f1": f1s})
        log.info("tune %s -> mean val macro-F1 %.4f", ov["pretrain"], results[-1]["mean_val_f1"])
    best = max(results, key=lambda r: r["mean_val_f1"])
    out = Path(a.out or f"configs/tuned_{a.dataset}.yaml")
    out.write_text("# generated by gcids.tune on validation data only\n" + yaml.safe_dump(
        {"pretrain": {"tau": best["tau"], "lr": best["lr"], "sigma": best["sigma"]}}, sort_keys=False))
    Path(str(out).replace(".yaml", "_grid.yaml")).write_text(yaml.safe_dump(results, sort_keys=False))
    log.info("best %s written to %s", best, out)


if __name__ == "__main__":
    main()
